# 判「已经张开」的开度门槛（行程百分比）。
#
# ★ 不能用「夹爪指令首次 ≤ CLOSE_PCT」来定抓取帧：home 位形复位后稳定下来是 −0.742%
#   （名义 1.9% 本就贴着下限），于是那个判据在某些集上命中**第 0 帧** —— 拿 home 的臂位形
#   当抓取位姿，量出 45.21mm 的假瞄点残差、2 帧的假夹住窗口。真值都不是那样。
#   正确的判据是「张开之后的首次合拢」，与量真机夹爪时用的同一套（真机 9 源 265 集验过）。
OPENED_PCT = 15.0


def close_frame(actions, close_pct):
    """抓取帧：夹爪**张开之后**首次合到底的那一帧。

    Args:
        actions: `(帧数, 6)` 真机口径动作，第 6 列是夹爪行程百分比。
        close_pct: 该场景的合拢指令值，取 `CLOSE_PCT[SCENES[场景]["real_task"]]` ——
            它逐任务不同（cube 1.27 / can 1.735，都是真机实测的"扳机到底"），
            所以不能在这里读全局常量。

    Returns:
        帧号；这一集没有「先张开再合到底」就给 `None`。
    """
    import numpy as np
    grip = np.asarray(actions, float)[:, 5]
    opened = np.flatnonzero(grip > OPENED_PCT)
    if not len(opened):
        return None
    # 容差取**一个夹爪计数**，不是 1e-6：指令会被量化到编码器栅格上，
    # 合拢值 1.27 量化后是 1.2698 或 1.3492，用 1e-6 的容差会一集都认不出来
    # （实测：`close_frame` 全数返回 None，抖动探针因此报「没判到集」）。
    # 容差取一个夹爪计数：全仓只有一个量子（标定是机器的属性，不按场景分）。
    closed = np.flatnonzero(grip[opened[0]:] <= close_pct + grip_step_pct())
    return int(opened[0] + closed[0]) if len(closed) else None


def held_window(actions, close_pct, grip_step):
    """堵转段的帧区间 `[起, 止)` —— 从合到底那一帧起，到夹爪再次张开之前。

    Args:
        actions: `(帧数, 6)` 真机口径动作。
        close_pct: 该场景的合拢指令值，取 `CLOSE_PCT[SCENES[场景]["real_task"]]`。
        grip_step: 夹爪编码器计数，取 `grip_step_pct()`，用作合拢判据的容差。

    Returns:
        `(起, 止)`；这一集没有「张开后合到底」就给 `None`。

    ★ **这个定义只此一处，别在工具里重推。** 重推过两次，两次都翻车：一次把集开头
      空爪停在 home 那一段当成搬运段（300 集里它的起点分位中位 0.000），据此判定真机
      夹爪不报爪口宽度；一次把回家合爪那一段也算进来，抖动量从 0.16 报成 15.16 次/秒。
      重推出来的窗口在旧参数下碰巧对，参数一动就静默指向别处，而且不报错。
    """
    import numpy as np
    start = close_frame(actions, close_pct)
    if start is None:
        return None
    after = np.flatnonzero(actions[start:, 5] > close_pct + grip_step)
    return start, (start + int(after[0]) if len(after) else len(actions))


