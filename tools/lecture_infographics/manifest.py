from __future__ import annotations

from dataclasses import dataclass
from typing import Literal


@dataclass(frozen=True)
class FigureSpec:
    key: str
    lecture: int
    number: int
    template: Literal["A", "B", "C"]
    title: str
    subtitle: str
    takeaway: str
    labels: tuple[str, ...]
    steps: tuple[str, ...] = ()


def figure(key: str, template: Literal["A", "B", "C"], title: str,
           subtitle: str, takeaway: str, labels: tuple[str, ...],
           steps: tuple[str, ...] = ()) -> FigureSpec:
    lecture, number = (int(value) for value in key.split("-"))
    return FigureSpec(key, lecture, number, template, title, subtitle,
                      takeaway, labels, steps)


